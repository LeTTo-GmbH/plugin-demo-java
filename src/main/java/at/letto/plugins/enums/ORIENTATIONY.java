package at.letto.plugins.enums;

/**
 * Vertikale Ausrichtung eines Textes an seinem Bezugspunkt.
 */
public enum ORIENTATIONY {
    /**
     * Ausrichtung an der unteren Textkante.
     */
    BOTTOM,
    /**
     * Zentrierte Ausrichtung.
     */
    CENTER,
    /**
     * Ausrichtung an der oberen Textkante.
     */
    TOP
}
